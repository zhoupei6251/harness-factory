#!/usr/bin/env node
// install-agents.ts — 从 agents/ 契约生成各平台的薄包装。
// 契约是唯一事实源；目标项目的 agent 文件是生成物，勿手改。
import { readFile, writeFile, mkdir, stat, readdir } from "node:fs/promises";
import { join, resolve, dirname } from "node:path";
import { homedir } from "node:os";
import { fileURLToPath } from "node:url";
import { loadPlatforms } from "./platforms.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const AGENTS_DIR = join(ROOT, "agents");
const MARKER = "generated by harness-factory/scripts/install-agents.ts";

interface AgentMeta {
  slug: string;
  description: string;
  generate: boolean;
  /** Wrapper file/agent name. Defaults to harness-<slug>; set it when an existing agent type must keep its name. */
  name?: string;
  type: string;
  model: string;
  readonly: boolean;
  skills: string[];
}

function wrapperName(meta: AgentMeta): string {
  return meta.name ?? `harness-${meta.slug}`;
}

function parseArgs(argv: string[], known: string[]) {
  let base = homedir();
  let dryRun = false;
  let force = false;
  const platforms = new Set<string>();
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--help" || arg === "-h") {
      console.log(
        "Usage: install-agents.ts [--platform claude|all] [--target <project>] [--force] [--dry-run]\n" +
          "Generates thin platform wrappers from agents/<slug>.md. Only hosts with a per-agent file concept are supported.",
      );
      process.exit(0);
    }
    if (arg === "--dry-run") {
      dryRun = true;
      continue;
    }
    if (arg === "--force") {
      force = true;
      continue;
    }
    if (!["--platform", "--target"].includes(arg)) throw new Error(`Unknown argument: ${arg}`);
    const value = argv[++i];
    if (!value || value.startsWith("--")) throw new Error(`Missing value for ${arg}`);
    if (arg === "--platform") {
      if (value === "all") for (const key of known) platforms.add(key);
      else if (known.includes(value)) platforms.add(value);
      else throw new Error(`Platform ${value} has no per-agent file concept; supported: ${known.join(", ")}`);
    } else {
      base = resolve(value);
    }
  }
  return { platforms: platforms.size ? [...platforms] : known, base, dryRun, force };
}

async function loadMeta(): Promise<AgentMeta[]> {
  const raw = await readFile(join(AGENTS_DIR, "index.json"), "utf-8");
  const parsed = JSON.parse(raw) as { agents?: AgentMeta[] };
  if (!Array.isArray(parsed.agents) || parsed.agents.length === 0) {
    throw new Error("agents/index.json must carry a non-empty agents array");
  }
  for (const meta of parsed.agents) {
    for (const key of ["slug", "description", "type", "model"] as const) {
      if (!meta[key]) throw new Error(`agents/index.json entry is missing ${key}`);
    }
    if (!Array.isArray(meta.skills)) throw new Error(`agents/index.json ${meta.slug} needs a skills array (may be empty)`);
    const contract = join(AGENTS_DIR, `${meta.slug}.md`);
    if (!(await stat(contract)).isFile()) throw new Error(`agents/${meta.slug}.md is missing`);
  }
  const onDisk = (await readdir(AGENTS_DIR)).filter((f) => f.endsWith(".md") && f !== "README.md").map((f) => f.slice(0, -3));
  const declared = new Set(parsed.agents.map((m) => m.slug));
  for (const slug of onDisk) {
    if (!declared.has(slug)) throw new Error(`agents/${slug}.md has no entry in agents/index.json`);
  }
  return parsed.agents;
}

function render(meta: AgentMeta, platform: string): string {
  const name = wrapperName(meta);
  const lines = [
    "---",
    `name: ${name}`,
    `platform: ${platform}`,
    `type: ${meta.type}`,
    `model: ${meta.model}`,
    `readonly: ${meta.readonly}`,
    `core: harness-factory/agents/${meta.slug}.md`,
  ];
  if (meta.skills.length) lines.push("skills:", ...meta.skills.map((s) => `  - ${s}`));
  lines.push("---", `<!-- ${MARKER} — edit agents/${meta.slug}.md instead -->`, `# ${name}`, "");
  lines.push(`你是${meta.description}。`, "");
  lines.push(`**先 Read \`harness-factory/agents/${meta.slug}.md\`** — 完整行为契约。`);
  if (meta.readonly) lines.push("", "只读：不改任何文件。");
  lines.push("");
  return lines.join("\n");
}

async function install(meta: AgentMeta, platform: string, destRoot: string, dryRun: boolean, force: boolean) {
  const dst = join(destRoot, `${wrapperName(meta)}.md`);
  const content = render(meta, platform);
  const existing = await readFile(dst, "utf-8").catch((error: NodeJS.ErrnoException) => {
    if (error.code!== "ENOENT") throw error;
    return null;
  });
  if (existing === content) {
    console.log(`[keep] ${dst}`);
    return "kept";
  }
  if (existing !== null && !existing.includes(MARKER) && !force) {
    console.error(`[conflict] ${dst} is not a generated file; re-run with --force to overwrite`);
    return "conflict";
  }
  if (!dryRun) {
    await mkdir(destRoot, { recursive: true });
    await writeFile(dst, content, "utf-8");
  }
  console.log(`[${dryRun ? "plan" : "ok"}] ${dst}`);
  return existing === null ? "installed" : "updated";
}

try {
  const matrix = await loadPlatforms();
  const known = [...matrix.values()].filter((c) => c.agentsDir !== null).map((c) => c.id).sort();
  const { platforms, base, dryRun, force } = parseArgs(process.argv.slice(2), known);
  const agents = await loadMeta();
  const generated = agents.filter((a) => a.generate);
  console.log(`${generated.length} agents; hosts: ${platforms.join(", ")}; ${dryRun ? "preview" : "install"}`);
  const counts = { installed: 0, updated: 0, kept: 0, conflict: 0 };
  for (const platform of platforms) {
    const destRoot = join(base, matrix.get(platform)!.agentsDir!);
    for (const meta of generated) {
      counts[await install(meta, platform, destRoot, dryRun, force)]++;
    }
  }
  console.log(
    `${dryRun ? "Planned" : "Installed"}: ${counts.installed} new, ${counts.updated} updated, ${counts.kept} unchanged, ${counts.conflict} conflicts. No plugins, hooks or MCP settings changed.`,
  );
  if (counts.conflict) process.exitCode = 1;
} catch (error) {
  console.error(`[FAIL] ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
}
