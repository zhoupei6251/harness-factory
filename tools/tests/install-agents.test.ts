import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const sandbox = await mkdtemp(join(tmpdir(), "harness-agents-"));
const target = join(sandbox, "project");
const generated = ["coder", "debugger", "explorer", "implementer", "leader-code", "reviewer", "test-engineer", "web-investigator"];
const expectedFiles = ["harness-coder", "harness-debugger", "harness-explorer", "harness-implementer", "leader-code", "reviewer", "harness-test-engineer", "harness-web-investigator"];

function run(args: string[]) {
  return spawnSync(
    process.execPath,
    [join(root, "node_modules/tsx/dist/cli.mjs"), join(root, "tools/scripts/install-agents.ts"), ...args],
    { encoding: "utf8", timeout: 30000 },
  );
}

try {
  const first = run(["--platform", "claude", "--target", target]);
  assert.equal(first.status, 0, first.stderr);
  assert.match(first.stdout, /Installed: 8 new/);

  const files = (await readdir(join(target, ".claude", "agents"))).sort();
  assert.deepEqual(files, expectedFiles.map((n) => `${n}.md`).sort(), "one wrapper per generated agent, named as declared");

  const reviewer = await readFile(join(target, ".claude", "agents", "reviewer.md"), "utf-8");
  assert.match(reviewer, /^---\nname: reviewer\n/, "a declared name overrides the harness- prefix");
  assert.match(reviewer, /core: harness-factory\/agents\/reviewer\.md/, "wrapper points at the canonical contract");
  assert.match(reviewer, /readonly: true/, "readonly survives generation");
  assert.match(reviewer, /generated by harness-factory/, "generated marker is present");

  const coder = await readFile(join(target, ".claude", "agents", "harness-coder.md"), "utf-8");
  assert.match(coder, /readonly: false/);
  assert.doesNotMatch(coder, /只读：不改任何文件/, "writable agents must not claim to be readonly");

  const again = run(["--platform", "claude", "--target", target]);
  assert.equal(again.status, 0);
  assert.match(again.stdout, /0 new, 0 updated, 8 unchanged/, "re-running is idempotent");

  // A hand-written file without the marker must never be silently clobbered.
  const handWritten = join(target, ".claude", "agents", "harness-explorer.md");
  await writeFile(handWritten, "# my own explorer\n", "utf-8");
  const blocked = run(["--platform", "claude", "--target", target]);
  assert.equal(blocked.status, 1, "conflict exits non-zero");
  assert.match(blocked.stderr, /is not a generated file/);
  assert.equal(await readFile(handWritten, "utf-8"), "# my own explorer\n", "hand-written file untouched");

  const forced = run(["--platform", "claude", "--target", target, "--force"]);
  assert.equal(forced.status, 0);
  assert.match(await readFile(handWritten, "utf-8"), /generated by harness-factory/);

  // Codex has no per-agent file concept; asking for it must fail loudly, not silently do nothing.
  const codex = run(["--platform", "codex", "--target", target]);
  assert.equal(codex.status, 1);
  assert.match(codex.stderr, /no per-agent file concept/);

  // index.json must cover every contract on disk, so a new agents/<role>.md cannot go unregistered.
  const index = JSON.parse(await readFile(join(root, "agents", "index.json"), "utf-8"));
  const contracts = (await readdir(join(root, "agents")))
    .filter((f) => f.endsWith(".md") && f !== "README.md").map((f) => f.slice(0, -3)).sort();
  assert.deepEqual(index.agents.map((a: { slug: string }) => a.slug).sort(), contracts,
    "agents/index.json and agents/*.md must stay in sync");

  console.log("install-agents: all assertions passed");
} finally {
  await rm(sandbox, { recursive: true, force: true });
}
